"""Embed the plugin guide (plugins/README.md) in the firmware, compressed.

Writes include/plugin_guide.h. The MCP server's plugin_guide tool unpacks it
(with the inflater in the chip's ROM) for an agent that writes a plugin, so
the guide it reads is the one for the plugin API this firmware has. Runs
before every build, like htmlconvert.py.

The header is committed, like html_portal.h: PlatformIO counts the files in
include/ in its project checksum, and a header that first appears during a
build makes the updater's build (include_updater.py) take the project for
changed and wipe .pio/build, the build in progress included.
"""

import os
import zlib

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    PROJECT_DIR = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))


def generate():
    with open(os.path.join(PROJECT_DIR, "plugins", "README.md"), "rb") as handle:
        guide = handle.read()
    packed = zlib.compress(guide, 9)
    rows = [", ".join("0x%02x" % b for b in packed[i:i + 16]) for i in range(0, len(packed), 16)]
    header = (
        "// Generated by guide2c.py from plugins/README.md - do not edit!\n"
        "#pragma once\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "static const size_t PLUGIN_GUIDE_SIZE = %d;  // unpacked\n"
        "static const uint8_t PLUGIN_GUIDE_ZLIB[] = {\n    %s\n};\n" % (len(guide), ",\n    ".join(rows))
    )
    path = os.path.join(PROJECT_DIR, "include", "plugin_guide.h")
    try:
        with open(path, "r") as handle:
            if handle.read() == header:
                return  # unchanged: leave it, so nothing is rebuilt for it
    except OSError:
        pass
    with open(path, "w") as handle:
        handle.write(header)
    print("guide2c: %d bytes of plugin guide, %d compressed" % (len(guide), len(packed)))


generate()
